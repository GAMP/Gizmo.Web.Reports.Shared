using System.ComponentModel.DataAnnotations;

namespace Gizmo.Web.Reports
{
    /// <summary>
    /// Represent report ranges.
    /// </summary>
    public enum ReportRangeType
    {
        /// <summary>
        /// Custom date/time ranges.
        /// </summary>
        [Name("Custom", nameof(Shared.Autogenerated.Resources.REPORT_RANGE_TYPE_CUSTOM_NAME))]
        Custom = 0,
        /// <summary>
        /// Current day range.
        /// </summary>
        [Name("Current day", nameof(Shared.Autogenerated.Resources.REPORT_RANGE_TYPE_CURRENT_DAY_NAME))]
        Day = 1,
        /// <summary>
        /// Current week range.
        /// </summary>
        [Name("Current week", nameof(Shared.Autogenerated.Resources.REPORT_RANGE_TYPE_CURRENT_WEEK_NAME))]
        Week = 2,
        /// <summary>
        /// Current month range.
        /// </summary>
        [Name("Current month", nameof(Shared.Autogenerated.Resources.REPORT_RANGE_TYPE_CURRENT_MONT_NAME))]
        Month = 3,
        /// <summary>
        /// Current year range.
        /// </summary>
        [Name("Current year", nameof(Shared.Autogenerated.Resources.REPORT_RANGE_TYPE_CURRENT_YEAR_NAME))]
        Year = 4,
    }
}
